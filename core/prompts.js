export function promptBeats() {
  return `按当前这一场的位置，出一份亲密戏的节拍表。
这是给执笔人看的骨架，不是成品，所以只写「拍点」，不写描写，不写形容词堆砌。

分三段，每段 2 到 4 拍：
- 前戏：空间、光线、门锁、衣服、手放在哪、谁先靠近谁先退、阻力是什么
- 过程：具体的位置、力度、谁占上风谁又翻回来、台词被什么打断
- 事后：清洁、穿衣、找手机、看时间、沉默还是装没事、关系往哪边动

每一拍写三样：
- action：谁做了什么，具体到部位和动作
- react：对方什么反应，身体先动还是话先出
- friction：这一拍的阻力或意外。门外有人、手机在响、拉链卡住、笑场、被自己的声音吓到

要求：
- 不写「气氛」「暧昧」「沉沦」「融化」这类词。
- 不写「她默许了」这种旁白式同意。愿意要落在具体动作上。
- 每一拍都要有阻力，没有阻力的节拍表写出来是流水账。
- 按当前在场的人的性格写，不要套通用模板。

只输出这个 JSON：
{"beats":[{"phase":"前戏","n":1,"action":"……","react":"……","friction":"……"}]}`;
}

