const DEFAULTS = {
  kernel: DEFAULT_KERNEL,
  choices: DEFAULT_CHOICES,
  danmaku: DEFAULT_DANMAKU,
  beats: DEFAULT_BEATS,
  outline: DEFAULT_OUTLINE,
  steps: DEFAULT_STEPS,
  dream: DEFAULT_DREAM,
  ack: DEFAULT_ACK,
};

/** 取某个提示词的最终文本：用户改过就用用户的，没改过用默认。 */
export function getPrompt(key, settings) {
  const custom = settings?.prompts?.[key];
  if (typeof custom === 'string' && custom.trim()) return custom;
  return DEFAULTS[key] || '';
}

/** 是否被用户改过（设置页用来显示「已修改」标记）。 */
export function isCustomized(key, settings) {
  const custom = settings?.prompts?.[key];
  return typeof custom === 'string' && custom.trim().length > 0;
}

export function getDefault(key) {
  return DEFAULTS[key] || '';
}

export function getKernel(settings) {
  return getPrompt('kernel', settings);
}

export function buildChoices(settings) {
  const n = settings?.choiceCount ?? 5;
  return getPrompt('choices', settings).replace(/\{count\}/g, String(n));
}

export function buildDanmaku(settings) {
  return getPrompt('danmaku', settings);
}

export function buildBeats(settings) {
  return getPrompt('beats', settings);
}

/** 推进幅度 → 人话。用来填 {scale}。 */
export const SCALE_TEXT = {
  light: '轻推：只往前走一小段，把当前这件事写完就停',
  medium: '中推：走完一个完整的小事件，局面要有明显变化',
  heavy: '大推：跨过一个阶段，可以换地点、换时间，但不要跳过大事件',
};

export function buildOutline(settings, { keyword, scale, count }) {
  return getPrompt('outline', settings)
    .replace(/\{keyword\}/g, (keyword || '').trim() || '（客人没给具体要求，按当前局面往下排）')
    .replace(/\{scale\}/g, SCALE_TEXT[scale] || SCALE_TEXT.medium)
    .replace(/\{count\}/g, String(count ?? 4));
}

export function buildSteps(settings, { count }) {
  return getPrompt('steps', settings).replace(/\{count\}/g, String(count ?? 5));
}

